import type {
  SystemOneChoiceAnswer,
  SystemOneNoulAnswer,
  SystemOnePolicyDecision,
  SystemOneScoreAnswer,
  SystemOneTypedAnswers,
  TypeSafeDetectionResponse,
} from "@/lib/types";
import { backendUrl } from "@/lib/backend-url";
import { DEFAULT_PROVIDER_SETTINGS, normalizeBaseUrl } from "@/lib/provider-settings";

// Server-side proxy for the online System One detection: the browser posts the
// text plus the user's provider settings (kept in localStorage), and this route
// forwards them to the provider endpoint. Going through the server avoids CORS
// restrictions on direct browser calls; the API key is only ever forwarded
// with the current request, never stored.

const PROVIDER_TIMEOUT_MS = 45_000;

// The analysis rows (style features + raw-LM perplexity) are model-independent
// and computed by the local backend, same as for local detections. ponytail:
// best-effort fetch — when the backend is down the online result carries no
// rows; lift into a pure-JS fallback if backend-free online mode ever matters.
async function fetchLocalDetails(text: string): Promise<TypeSafeDetectionResponse["details"]> {
  try {
    const res = await fetch(backendUrl("/details"), {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ text }),
      signal: AbortSignal.timeout(20_000),
    });
    if (!res.ok) return [];
    const data = (await res.json()) as { details?: TypeSafeDetectionResponse["details"] };
    return data.details ?? [];
  } catch {
    return [];
  }
}

// Questions mirror the local System One pipeline (aitextd SYSTEM_ONE_*
// constants) so the
// online and local typed answers are directly comparable.
const CHOICE_CANDIDATES = ["human_written", "ai_generated"] as const;
const SCORE_LEVEL_COUNT = 5; // definitely_human .. definitely_ai

const QUESTIONS = {
  source: {
    type: "choice" as const,
    instructions:
      "Where does this text come from? Decide whether it was written by a human or generated by an AI language model.",
    criteria: {
      human_written:
        "Written by a human. Natural variation in rhythm and sentence length, a personal voice, idiomatic flow, and small imperfections or idiosyncratic phrasing.",
      ai_generated:
        "Generated by an AI language model. Uniformly polished and fluent, templated rhythm, generic phrasing, evenly structured sentences, and low burstiness.",
    },
  },
  machine_likeness: {
    type: "score" as const,
    instructions: "How machine-like is the writing style of this text?",
    criteria: [
      "Unmistakably human writing: strong personal voice, irregular rhythm, idioms or colloquialisms, and natural digressions.",
      "Mostly human writing with light editing or simple structure; some uniformity but an authentic voice remains.",
      "Ambiguous: a mix of natural human touches and polished machine-like uniformity; cannot lean either way.",
      "Mostly machine-like: fluent but generic, evenly structured sentences, templated transitions, and little personal voice.",
      "Strongly machine-like: perfectly uniform polish, formulaic structure, generic vocabulary, and no personal voice or irregularity.",
    ],
  },
  needs_review: {
    type: "noul" as const,
    instructions:
      "Should a human expert review this text before its AI-or-human origin is acted upon?",
    criteria: {
      true: "Yes — the evidence is ambiguous or a wrong automatic decision would be costly; expert review is warranted.",
      false:
        "No — the origin (human-written or AI-generated) is clear enough to act on automatically.",
    },
  },
};

interface ProviderBody {
  text?: string;
  provider?: {
    baseUrl?: string;
    model?: string;
    apiKey?: string;
  };
}

interface SystemOneResponse {
  model?: string;
  answers?: Record<string, Record<string, unknown>>;
  usage?: { input_tokens?: number; output_tokens?: number };
}

function providerError(status: number): string {
  switch (status) {
    case 401:
      return "کلید API نامعتبر است یا منقضی شده؛ پیکربندی سرویس آنلاین را بررسی کنید.";
    case 422:
      return "درخواست ارسالی نامعتبر است؛ تنظیمات سرویس (آدرس و نام مدل) را بررسی کنید.";
    case 429:
      return "محدودیت نرخ درخواست سرویس آنلاین فعال شده؛ کمی بعد دوباره تلاش کنید.";
    case 529:
      return "سرویس آنلاین در حال حاضر شلوغ است؛ کمی بعد دوباره تلاش کنید.";
    default:
      return `خطای سرویس آنلاین (کد ${status})؛ بعداً دوباره تلاش کنید.`;
  }
}

function errorMessage(err: unknown): string {
  if (err instanceof Error) {
    if (err.name === "TimeoutError" || err.name === "AbortError") {
      return "زمان انتظار پاسخ سرویس آنلاین به پایان رسید؛ دوباره تلاش کنید.";
    }
    return "اتصال به سرویس آنلاین برقرار نشد؛ آدرس سرویس و اتصال اینترنت را بررسی کنید.";
  }
  return "خطای ناشناخته در تماس با سرویس آنلاین.";
}

function topOption(probabilities: Record<string, number>): (typeof CHOICE_CANDIDATES)[number] {
  let best: (typeof CHOICE_CANDIDATES)[number] = CHOICE_CANDIDATES[0];
  for (const candidate of CHOICE_CANDIDATES) {
    if ((probabilities[candidate] ?? 0) > (probabilities[best] ?? 0)) best = candidate;
  }
  return best;
}

function buildPolicy(confidence: number): SystemOnePolicyDecision {
  // Same thresholds as the local System One checkpoint so both sides' policy
  // tiers are comparable (aitextd/constants.py + aitextd/system_one.py:
  // proceed >= 0.8, needs review >= 0.6).
  if (confidence >= 0.8) {
    return {
      tier: "proceed",
      tierFa: "ادامه",
      descriptionFa: "اطمینان مدل بالاست؛ تصمیم خودکار قابل‌اعتماد است.",
    };
  }
  if (confidence >= 0.6) {
    return {
      tier: "needs_review",
      tierFa: "نیازمند بازبینی انسانی",
      descriptionFa: "پاسخ مدل در ناحیه مرزی است؛ پیش از اقدام، بازبینی انسانی توصیه می‌شود.",
    };
  }
  return {
    tier: "low_confidence",
    tierFa: "اطمینان پایین",
    descriptionFa: "اطمینان مدل کم است؛ تصمیم خودکار توصیه نمی‌شود.",
  };
}

function mapTypedAnswers(data: SystemOneResponse): {
  typedAnswers: SystemOneTypedAnswers;
  choiceConfidence: number;
} {
  const answers = data.answers ?? {};

  const choiceAnswer = answers.source ?? {};
  const choiceProbabilities = (choiceAnswer.probabilities ?? {}) as Record<string, number>;
  const choiceProbs = CHOICE_CANDIDATES.map((c) => choiceProbabilities[c] ?? 0);
  const choiceTop = topOption(choiceProbabilities);
  const isAI = choiceTop === "ai_generated";
  const choiceConfidence =
    typeof choiceAnswer.confidence === "number" ? choiceAnswer.confidence : 0;

  const scoreAnswer = answers.machine_likeness ?? {};
  const scoreProbabilities = (scoreAnswer.probabilities ?? {}) as Record<string, number>;
  const scoreProbs = Array.from(
    { length: SCORE_LEVEL_COUNT },
    (_, i) => scoreProbabilities[String(i)] ?? 0,
  );
  const scoreIdx = scoreProbs.indexOf(Math.max(...scoreProbs));
  const scoreValue = typeof scoreAnswer.score === "number" ? scoreAnswer.score : scoreIdx;

  const noulProbability =
    typeof answers.needs_review?.noul === "number" ? (answers.needs_review.noul as number) : 0;

  const maxChoiceProb = Math.max(...choiceProbs);

  const choice: SystemOneChoiceAnswer = {
    question: "Where does this text come from?",
    questionFa: "این متن از کجا آمده است؟",
    candidates: [...CHOICE_CANDIDATES],
    candidateLabelsFa: ["نوشته انسان", "تولیدشده توسط هوش مصنوعی"],
    probabilities: choiceProbs.map((p) => Math.round(p * 10000) / 10000),
    answer: choiceTop,
    answerFa: isAI ? "تولیدشده توسط هوش مصنوعی" : "نوشته انسان",
  };

  const score: SystemOneScoreAnswer = {
    question: "How machine-like is the writing style?",
    questionFa: "سبک نوشتار چقدر ماشین‌مانند است؟",
    levels: ["definitely_human", "probably_human", "mixed_signals", "probably_ai", "definitely_ai"],
    levelLabelsFa: [
      "قطعاً انسان",
      "احتمالاً انسان",
      "سیگنال‌های ترکیبی",
      "احتمالاً هوش مصنوعی",
      "قطعاً هوش مصنوعی",
    ],
    probabilities: scoreProbs.map((p) => Math.round(p * 10000) / 10000),
    value: Math.round(scoreValue * 1000) / 1000,
    answer: ["definitely_human", "probably_human", "mixed_signals", "probably_ai", "definitely_ai"][
      scoreIdx
    ],
    answerFa: [
      "قطعاً انسان",
      "احتمالاً انسان",
      "سیگنال‌های ترکیبی",
      "احتمالاً هوش مصنوعی",
      "قطعاً هوش مصنوعی",
    ][scoreIdx],
  };

  const noul: SystemOneNoulAnswer = {
    question: "Does this text need human review?",
    questionFa: "آیا این متن نیاز به بازبینی انسانی دارد؟",
    probability: Math.round(noulProbability * 10000) / 10000,
    answer: noulProbability >= 0.5,
    answerFa: noulProbability >= 0.5 ? "بله" : "خیر",
  };

  return {
    typedAnswers: { choice, score, noul, policy: buildPolicy(maxChoiceProb) },
    choiceConfidence,
  };
}

export async function POST(request: Request) {
  let body: ProviderBody;
  try {
    body = await request.json();
  } catch {
    return Response.json({ error: "بدنه درخواست نامعتبر است." }, { status: 400 });
  }

  const text = body.text?.trim() ?? "";
  if (text.length < 20) {
    return Response.json({ error: "متن ارسال شده باید حداقل ۲۰ کاراکتر باشد." }, { status: 400 });
  }

  const apiKey = body.provider?.apiKey?.trim() ?? "";
  if (!apiKey) {
    return Response.json(
      { error: "برای تحلیل آنلاین، ابتدا کلید API را در پیکربندی سرویس وارد کنید." },
      { status: 400 },
    );
  }

  const baseUrl = normalizeBaseUrl(body.provider?.baseUrl || DEFAULT_PROVIDER_SETTINGS.baseUrl);
  // Accept either a bare origin (path appended) or a full endpoint URL.
  const endpoint = baseUrl.endsWith("/v1/systemone") ? baseUrl : `${baseUrl}/v1/systemone`;
  const model = body.provider?.model?.trim() || DEFAULT_PROVIDER_SETTINGS.model;

  const detailsPromise = fetchLocalDetails(text);
  const startedAt = Date.now();
  let res: Response;
  try {
    res = await fetch(endpoint, {
      method: "POST",
      headers: {
        Authorization: `Bearer ${apiKey}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        state: { text },
        model,
        questions: QUESTIONS,
      }),
      signal: AbortSignal.timeout(PROVIDER_TIMEOUT_MS),
    });
  } catch (err) {
    return Response.json({ error: errorMessage(err) }, { status: 502 });
  }

  if (!res.ok) {
    return Response.json({ error: providerError(res.status) }, { status: res.status });
  }

  let data: SystemOneResponse;
  try {
    data = (await res.json()) as SystemOneResponse;
  } catch {
    return Response.json(
      { error: "پاسخ سرویس آنلاین قابل تفسیر نبود؛ دوباره تلاش کنید." },
      { status: 502 },
    );
  }

  const { typedAnswers, choiceConfidence } = mapTypedAnswers(data);
  const isAI = typedAnswers.choice.answer === "ai_generated";
  const confidence = Math.max(...typedAnswers.choice.probabilities);

  const result: TypeSafeDetectionResponse = {
    isAI,
    confidence: Math.round(confidence * 10000) / 10000,
    choiceConfidence: Math.round(choiceConfidence * 10000) / 10000,
    verdict: isAI
      ? "This text appears to be AI-generated."
      : "This text appears to be human-written.",
    verdictFa: isAI
      ? "این متن به نظر تولید شده توسط هوش مصنوعی است."
      : "این متن به نظر توسط انسان نوشته شده است.",
    details: await detailsPromise,
    modelUsed: model,
    textLength: text.length,
    wordCount: text.split(/\s+/).filter(Boolean).length,
    typedAnswers,
    requestedModel: model,
    resolvedModel: typeof data.model === "string" ? data.model : undefined,
    usage: data.usage
      ? {
          inputTokens: data.usage.input_tokens ?? 0,
          outputTokens: data.usage.output_tokens ?? 0,
        }
      : null,
    latencyMs: Date.now() - startedAt,
  };

  return Response.json(result);
}
