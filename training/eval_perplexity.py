"""Measure how well raw-LM perplexity separates human from AI-generated text.

The perplexity signal (aitextd.perplexity.gpt2_perplexity_batch) is training-free and
independent of every fine-tuned classifier -- exactly the kind of diverse
vote the weighted ensemble wants. Before giving it any weight, this script
answers the empirical question on the held-out test slice:

- ROC AUC of perplexity as an AI-detector score;
- the Youden-J threshold and the confusion counts at that threshold;
- per-class distribution summary (mean / median / p10 / p90), so the
  overlap between the two regimes is visible, not just the headline AUC.

The detection direction is MEASURED, not assumed. The textbook expectation
is "AI text scores lower perplexity under a reference LM", but the
reference-model mismatch can invert it: this dataset was generated by 70
much stronger LLMs, and a 124M GPT-2 may find their output MORE surprising
than human blogs. AUC < 0.5 means exactly that inversion -- still
information, but with the opposite sign, and a poor standalone detector.

Run from the project root: python training/eval_perplexity.py
Pass a number to evaluate on a smaller quick subset, e.g.
    python training/eval_perplexity.py 100
"""

import math
import sys
import time
from pathlib import Path

import numpy as np
import torch
from sklearn.metrics import roc_auc_score, roc_curve

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

from aitextd.perplexity import gpt2_perplexity_batch
from split import RANDOM_SEED, load_split

TEST_SUBSET = 1500  # same held-out slice convention as the other trainers

torch.set_num_threads(12)


def main():
    n = int(sys.argv[1]) if len(sys.argv) > 1 else TEST_SUBSET
    df, _, test_idx = load_split()
    y = df["aiGenerated"].to_numpy()
    if n < len(test_idx):
        rng = np.random.default_rng(RANDOM_SEED)
        test_idx = rng.choice(test_idx, size=n, replace=False)
    texts = [str(t) for t in df["text"].to_numpy()[test_idx]]
    y_test = y[test_idx]
    print(f"Scoring {len(texts)} held-out texts with raw GPT-2-fa perplexity...")

    start = time.time()
    ppl = gpt2_perplexity_batch(texts)
    print(f"Done in {time.time() - start:.0f}s")

    valid = ~np.isnan(ppl)
    if valid.sum() < len(ppl):
        print(f"Dropped {len(ppl) - valid.sum()} texts too short to score")
    ppl, y_valid = ppl[valid], y_test[valid]
    # Textbook direction: AI text more predictable -> score = -log(ppl). The
    # AUC below tells whether the data agrees (>= 0.5) or inverts it.
    score = -np.log(ppl)
    auc = float(roc_auc_score(y_valid, score))
    flipped = auc < 0.5
    print(f"\nROC AUC (perplexity as AI-detector): {auc:.4f}")
    if flipped:
        print("AUC < 0.5: signal INVERTED on this dataset -- the strong generator LLMs read")
        print("as MORE surprising to the 124M reference LM than human blogs.")
        print(f"Flip-adjusted AUC: {1 - auc:.4f}")

    # Youden-J threshold, searched in score space so the direction is handled
    # by the data, not the assumption.
    fpr, tpr, thresholds = roc_curve(y_valid, score)
    j = tpr - fpr
    best = int(np.argmax(j))
    thr_score = float(thresholds[best])
    preds = (score >= thr_score).astype(int)
    tp = int(((preds == 1) & (y_valid == 1)).sum())
    fp = int(((preds == 1) & (y_valid == 0)).sum())
    tn = int(((preds == 0) & (y_valid == 0)).sum())
    fn = int(((preds == 0) & (y_valid == 1)).sum())
    acc = (tp + tn) / len(y_valid)
    if thr_score >= 0:
        thr_desc = f"ppl <= {math.exp(-thr_score):.2f} -> AI"
    else:
        thr_desc = f"ppl >= {math.exp(-thr_score):.2f} -> AI (inverted)"
    print(f"Youden threshold: {thr_desc}  |  accuracy={acc:.4f}  tp={tp} fp={fp} tn={tn} fn={fn}")

    for name, cls in [("human", 0), ("ai", 1)]:
        p = ppl[y_valid == cls]
        if len(p):
            print(
                f"{name:>6}: n={len(p):<5} mean={p.mean():.1f} median={np.median(p):.1f} "
                f"p10={np.percentile(p, 10):.1f} p90={np.percentile(p, 90):.1f}"
            )


if __name__ == "__main__":
    main()
